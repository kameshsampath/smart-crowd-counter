#!/usr/bin/env node
// gen-schema-allowlist.mjs — regenerate __tests__/openshell/schema-allowlist.ts
// FROM the authoritative OpenShell schema reference (allowed-fields ALLOWLIST):
//   policy fields   <- https://docs.nvidia.com/openshell/latest/how-it-works/policies/schema (`.md`)
//   profile fields  <- https://docs.nvidia.com/openshell/latest/how-it-works/providers/profiles (`.md`)
// A field is legal only if the schema lists it, so an invented-but-plausible
// field (the bounded-boxer regression: masked_paths / default_egress /
// no_new_privileges) fails the CI conformance test.
//
// Usage: node scripts/openshell/gen-schema-allowlist.mjs   (needs network)
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

const DOCS = "https://docs.nvidia.com/openshell/latest"
const POLICY_URL = `${DOCS}/how-it-works/policies/schema.md`
const PROFILE_URL = `${DOCS}/how-it-works/providers/profiles.md`

// Enum VALUE tokens that legitimately appear in the first column of "Values"
// table rows; they are not field names.
const VALUE_TOKENS = new Set([
  "true", "false", "best_effort", "hard_requirement", "enforce", "audit",
  "skip", "full", "rest", "tcp", "websocket", "graphql", "mcp", "json-rpc",
  "read-only", "read-write", "sandbox", "other", "inference", "agent",
  "source_control", "messaging", "data", "knowledge",
])

async function fieldNames(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`fetch ${url}: HTTP ${res.status}`)
  const md = await res.text()
  const names = new Set()
  let inYaml = false
  for (const line of md.split("\n")) {
    if (/^```/.test(line.trim())) { inYaml = !inYaml; continue }
    const m = line.match(/^\|\s*`([a-z_0-9]+)`/)
    if (m && !VALUE_TOKENS.has(m[1])) names.add(m[1])
    // top-level keys inside yaml schema blocks (e.g. the Profile Schema block)
    if (inYaml) {
      const y = line.match(/^([a-z_0-9]+):/)
      if (y) names.add(y[1])
    }
  }
  return [...names].sort()
}

const policyFields = await fieldNames(POLICY_URL)
const profileFields = await fieldNames(PROFILE_URL)

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  "../../__tests__/openshell/schema-allowlist.ts")

const header = `// GENERATED by scripts/openshell/gen-schema-allowlist.mjs — do not edit by hand.
// Source of truth: NVIDIA OpenShell docs Latest (v0.1.8), fetched ${new Date().toISOString().slice(0, 10)}:
//   POLICY_FIELDS  <- ${POLICY_URL}
//   PROFILE_FIELDS <- ${PROFILE_URL}
// Cross-checked against github.com/NVIDIA/OpenShell @ f1ce6930710a76a5fac4d423b2c1b318ace3839b
// (crates/openshell-policy-schema). A field is legal only if listed here;
// unknown fields (e.g. masked_paths, default_egress, no_new_privileges) fail CI.
`

const body = `export const POLICY_FIELDS: ReadonlySet<string> = new Set(${JSON.stringify(policyFields, null, 2)})

export const PROFILE_FIELDS: ReadonlySet<string> = new Set(${JSON.stringify(profileFields, null, 2)})

// Profile credential/endpoint subfield allowlist (same schema reference).
export const PROFILE_CREDENTIAL_FIELDS: ReadonlySet<string> = new Set([
  "name", "description", "env_vars", "required", "auth_style", "header_name",
  "query_param", "path_template", "refresh", "stable_placeholder", "token_grant",
])
export const PROFILE_REFRESH_FIELDS: ReadonlySet<string> = new Set([
  "strategy", "token_url", "scopes", "refresh_before", "max_lifetime",
  "material", "additional_outputs",
])
export const PROFILE_ENDPOINT_FIELDS: ReadonlySet<string> = new Set(POLICY_FIELDS)
`
writeFileSync(out, header + body)
console.log(`wrote ${out}`)
console.log(`POLICY_FIELDS: ${policyFields.length} entries, PROFILE_FIELDS: ${profileFields.length} entries`)
